"""Offline, deterministic atlas builder. Raw snapshots are never modified."""
import csv, json, hashlib, re
from pathlib import Path
from collections import Counter
ROOT=Path(__file__).resolve().parents[1]
def read(p):
    with (ROOT/p).open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))
def write(p,rows,fields=None):
    with (ROOT/p).open('w',encoding='utf-8',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields or list(rows[0]));w.writeheader();w.writerows(rows)
def slug(s):return re.sub(r'[^a-z0-9]+','-',s.lower()).strip('-')
def build():
    films=[]
    for r in read('data/disney/disney_films.csv'):
        films.append(dict(id='disney-'+slug(r['film']),title=r['film'],year=int(r['release_year']),studio='Disney Animation',release_date=None,date_precision='year',source_url=r['source_url'],source_accessed=r['access_date'],verification='catalogue_snapshot; not independently rechecked'))
    for r in read('data/raw/pixar_films.csv'):
        films.append(dict(id='pixar-'+slug(r['film']),title=r['film'],year=int(r['release_date'][:4]),studio='Pixar',release_date=r['release_date'],date_precision='day',source_url='https://github.com/erictleung/pixarfilms/tree/e85a10a77b043d45fe8d950dbdf4d27886ccf520',source_accessed='2026-10-29',verification='community_snapshot; not independently rechecked'))
    films.sort(key=lambda x:(x['year'],x['id']))
    assert len(films)==95 and len({f['id'] for f in films})==95
    assert Counter(f['studio'] for f in films)=={'Disney Animation':64,'Pixar':31}
    ids={f['id'] for f in films}
    tables={name:read('data/annotations/'+name+'.csv') for name in ['film_themes','film_life_stages','film_relationships']}
    themes=['Friendship','Family','Love','Identity','Belonging','Independence','Fear','Loss','Purpose','Memory']
    stages=['Childhood','Adolescence','Adulthood','Later Life']
    for name,rows in tables.items():
        seen=set()
        for r in rows:
            assert r['film_id'] in ids,r
            assert all(r[k] for k in ['source_url','evidence','evidence_locator','coding_rule','coder','coded_at','review_status']),r
            assert r['review_status'] in ['source_checked_pending_human','human_reviewed']
            if name=='film_themes':assert r['theme'] in themes
            if name=='film_life_stages':assert r['life_stage'] in stages
            key=tuple(r.values());assert key not in seen;seen.add(key)
    ratings=[]
    by_title={f['title']:f for f in films if f['studio']=='Pixar'}
    for r in read('data/raw/public_response.csv'):
        score=float(r['imdb_score']);votes=int(r['imdb_counts']);assert 0<=score<=10 and votes>=0
        ratings.append(dict(film_id=by_title[r['film']]['id'],imdb_id='',averageRating=score,numVotes=votes,observed_at='',snapshot_acquired='2026-10-29',source_url=by_title[r['film']]['source_url'],review_status='historical_secondary_snapshot; IMDb ID and observation date unresolved'))
    # Optional permitted IMDb refresh, generated by import_imdb.py; require explicit reviewed mapping.
    imported=ROOT/'data/annotations/imdb_ratings_verified.csv'
    if imported.exists():
        updates=read('data/annotations/imdb_ratings_verified.csv'); refreshed={r['film_id'] for r in updates}
        for r in updates:
            assert r['film_id'] in ids and re.fullmatch(r'tt\d+',r['imdb_id'])
            assert 0<=float(r['averageRating'])<=10 and int(r['numVotes'])>=0
        ratings=[r for r in ratings if r['film_id'] not in refreshed]+updates
    write('data/processed/films_master.csv',films)
    write('data/processed/imdb_ratings.csv',ratings)
    for f in films:
        f['themes']=[r for r in tables['film_themes'] if r['film_id']==f['id']]
        f['life_stages']=[r for r in tables['film_life_stages'] if r['film_id']==f['id']]
        f['relationships']=[r for r in tables['film_relationships'] if r['film_id']==f['id']]
        f['rating']=next((r for r in ratings if r['film_id']==f['id']),None)
        f['annotation_status']='partial_source_checked_pending_human' if f['themes'] else 'uncoded'
    coverage={'films':len(films),'studios':dict(Counter(f['studio'] for f in films)),'theme_films':sum(bool(f['themes']) for f in films),'life_stage_films':sum(bool(f['life_stages']) for f in films),'relationship_films':sum(bool(f['relationships']) for f in films),'rating_films':len(ratings),'human_reviewed_theme_films':len({r['film_id'] for r in tables['film_themes'] if r['review_status']=='human_reviewed'}),'imdb_id_films':sum(bool(r['imdb_id']) for r in ratings)}
    manifest={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT/'data').rglob('*.csv'))}
    atlas={'films':films,'themes':themes,'life_stages':stages,'coverage':coverage,'built_as_of':'2026-11-12','method_version':'1.0','input_sha256':manifest}
    for p in ['public/atlas.json','data/processed/atlas.json']:(ROOT/p).write_text(json.dumps(atlas,ensure_ascii=False,indent=2)+'\n')
    (ROOT/'analysis/atlas_validation.json').write_text(json.dumps({'coverage':coverage,'checks':{'unique_ids':True,'foreign_keys':True,'evidence_required':True,'rating_ranges':True},'input_sha256':manifest},indent=2)+'\n')
    print(json.dumps(coverage,indent=2))
if __name__=='__main__':build()
